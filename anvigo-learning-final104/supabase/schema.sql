-- Enable UUID extension (usually pre-enabled in Supabase)
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- ------------------------------------------------------------
-- 1. Student Enrollments Table (Parents / Students seeking tuition)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.student_enrollments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    name TEXT NOT NULL,
    student_class TEXT,
    mobile TEXT NOT NULL,
    email TEXT,
    state TEXT NOT NULL,
    city TEXT NOT NULL,
    address TEXT NOT NULL,
    pincode TEXT NOT NULL,
    subjects TEXT NOT NULL,
    budget TEXT,
    status TEXT DEFAULT 'New' NOT NULL,
    notes TEXT,
    source TEXT DEFAULT 'website'
);

-- Indexes for fast search and admin filtering
CREATE INDEX IF NOT EXISTS idx_student_enrollments_created_at ON public.student_enrollments (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_student_enrollments_status ON public.student_enrollments (status);
CREATE INDEX IF NOT EXISTS idx_student_enrollments_city ON public.student_enrollments (city);
CREATE INDEX IF NOT EXISTS idx_student_enrollments_state ON public.student_enrollments (state);

-- ------------------------------------------------------------
-- 2. Teacher Applications Table (Tutors / Teachers applying for jobs)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.teacher_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    name TEXT NOT NULL,
    mobile TEXT NOT NULL,
    email TEXT,
    qualification TEXT,
    state TEXT NOT NULL,
    city TEXT NOT NULL,
    address TEXT NOT NULL,
    pincode TEXT NOT NULL,
    subjects TEXT NOT NULL,
    resume_url TEXT,
    status TEXT DEFAULT 'New' NOT NULL,
    notes TEXT,
    source TEXT DEFAULT 'website'
);

CREATE INDEX IF NOT EXISTS idx_teacher_applications_created_at ON public.teacher_applications (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_teacher_applications_status ON public.teacher_applications (status);
CREATE INDEX IF NOT EXISTS idx_teacher_applications_city ON public.teacher_applications (city);
CREATE INDEX IF NOT EXISTS idx_teacher_applications_state ON public.teacher_applications (state);

-- ------------------------------------------------------------
-- 3. School Requests Table (Schools hiring teachers)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.school_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    school_name TEXT NOT NULL,
    contact TEXT NOT NULL,
    email TEXT,
    state TEXT NOT NULL,
    city TEXT NOT NULL,
    address TEXT NOT NULL,
    pincode TEXT NOT NULL,
    subject TEXT NOT NULL,
    budget TEXT,
    status TEXT DEFAULT 'New' NOT NULL,
    notes TEXT,
    source TEXT DEFAULT 'website'
);

CREATE INDEX IF NOT EXISTS idx_school_requests_created_at ON public.school_requests (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_school_requests_status ON public.school_requests (status);
CREATE INDEX IF NOT EXISTS idx_school_requests_city ON public.school_requests (city);
CREATE INDEX IF NOT EXISTS idx_school_requests_state ON public.school_requests (state);

-- ------------------------------------------------------------
-- 4. Site Settings Table (Optional cloud sync for website content)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.site_settings (
    key TEXT PRIMARY KEY,
    value JSONB NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- ------------------------------------------------------------
-- 5. Row Level Security (RLS)
-- ------------------------------------------------------------
-- Enable RLS on all tables
ALTER TABLE public.student_enrollments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.teacher_applications ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.school_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.site_settings ENABLE ROW LEVEL SECURITY;

-- Drop existing policies if re-running script
DROP POLICY IF EXISTS "Public can insert student enrollments" ON public.student_enrollments;
DROP POLICY IF EXISTS "Admins or Anon can read student enrollments" ON public.student_enrollments;
DROP POLICY IF EXISTS "Admins can update student enrollments" ON public.student_enrollments;
DROP POLICY IF EXISTS "Admins can delete student enrollments" ON public.student_enrollments;

DROP POLICY IF EXISTS "Public can insert teacher applications" ON public.teacher_applications;
DROP POLICY IF EXISTS "Admins or Anon can read teacher applications" ON public.teacher_applications;
DROP POLICY IF EXISTS "Admins can update teacher applications" ON public.teacher_applications;
DROP POLICY IF EXISTS "Admins can delete teacher applications" ON public.teacher_applications;

DROP POLICY IF EXISTS "Public can insert school requests" ON public.school_requests;
DROP POLICY IF EXISTS "Admins or Anon can read school requests" ON public.school_requests;
DROP POLICY IF EXISTS "Admins can update school requests" ON public.school_requests;
DROP POLICY IF EXISTS "Admins can delete school requests" ON public.school_requests;

DROP POLICY IF EXISTS "Anyone can read site settings" ON public.site_settings;
DROP POLICY IF EXISTS "Authenticated can write site settings" ON public.site_settings;
DROP POLICY IF EXISTS "Admins or Anon can write site settings" ON public.site_settings;

-- POLICIES:
-- Allow anyone on the public website to submit forms (INSERT)
CREATE POLICY "Public can insert student enrollments"
    ON public.student_enrollments FOR INSERT
    WITH CHECK (true);

CREATE POLICY "Public can insert teacher applications"
    ON public.teacher_applications FOR INSERT
    WITH CHECK (true);

CREATE POLICY "Public can insert school requests"
    ON public.school_requests FOR INSERT
    WITH CHECK (true);

-- Allow Admin (either authenticated user OR via configured anon key) to manage records
CREATE POLICY "Admins or Anon can read student enrollments"
    ON public.student_enrollments FOR SELECT
    USING (true);

CREATE POLICY "Admins can update student enrollments"
    ON public.student_enrollments FOR UPDATE
    USING (true);

CREATE POLICY "Admins can delete student enrollments"
    ON public.student_enrollments FOR DELETE
    USING (true);

CREATE POLICY "Admins or Anon can read teacher applications"
    ON public.teacher_applications FOR SELECT
    USING (true);

CREATE POLICY "Admins can update teacher applications"
    ON public.teacher_applications FOR UPDATE
    USING (true);

CREATE POLICY "Admins can delete teacher applications"
    ON public.teacher_applications FOR DELETE
    USING (true);

CREATE POLICY "Admins or Anon can read school requests"
    ON public.school_requests FOR SELECT
    USING (true);

CREATE POLICY "Admins can update school requests"
    ON public.school_requests FOR UPDATE
    USING (true);

CREATE POLICY "Admins can delete school requests"
    ON public.school_requests FOR DELETE
    USING (true);

CREATE POLICY "Anyone can read site settings"
    ON public.site_settings FOR SELECT
    USING (true);

CREATE POLICY "Admins or Anon can write site settings"
    ON public.site_settings FOR ALL
    USING (true)
    WITH CHECK (true);

-- ------------------------------------------------------------
-- 6. Supabase Storage Buckets
-- ------------------------------------------------------------
-- Create storage buckets for resumes and website uploads
INSERT INTO storage.buckets (id, name, public)
VALUES ('resumes', 'resumes', true)
ON CONFLICT (id) DO NOTHING;

INSERT INTO storage.buckets (id, name, public)
VALUES ('site-uploads', 'site-uploads', true)
ON CONFLICT (id) DO NOTHING;

-- Storage Policies for 'resumes' bucket
DROP POLICY IF EXISTS "Public can upload resumes" ON storage.objects;
DROP POLICY IF EXISTS "Public can read resumes" ON storage.objects;

CREATE POLICY "Public can upload resumes"
    ON storage.objects FOR INSERT
    WITH CHECK (bucket_id = 'resumes');

CREATE POLICY "Public can read resumes"
    ON storage.objects FOR SELECT
    USING (bucket_id = 'resumes');

-- Storage Policies for 'site-uploads' bucket
DROP POLICY IF EXISTS "Public can view site uploads" ON storage.objects;
DROP POLICY IF EXISTS "Admins can manage site uploads" ON storage.objects;

CREATE POLICY "Public can view site uploads"
    ON storage.objects FOR SELECT
    USING (bucket_id = 'site-uploads');

CREATE POLICY "Admins can manage site uploads"
    ON storage.objects FOR ALL
    USING (bucket_id = 'site-uploads');

